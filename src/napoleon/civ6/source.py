"""What ``Civ6Backend`` needs from civ6-mcp.

The read and action methods have the names and arguments of civ6-mcp's ``GameState``,
so a ``GameState`` covers most of this as is. Results are civ6-mcp's dataclasses, read
by attribute, so the tests can stand in plain objects with the same fields.

Two methods are not on ``GameState``: ``end_turn_blockers`` and ``ready_unit_ids``.
``napoleon.civ6.live`` adds them with small Lua queries.

Action methods return civ6-mcp's result text. Text starting ``Error``, ``ERR`` or
``FAILED`` means the game refused the action.
"""

from __future__ import annotations

from typing import Any, Protocol


class Civ6Source(Protocol):
    # Reads (civ6-mcp GameState) ------------------------------------------------------
    async def get_game_overview(self) -> Any: ...
    async def get_units(self) -> list[Any]: ...
    async def get_cities(self) -> tuple[list[Any], list[str]]: ...
    async def get_tech_civics(self) -> Any: ...
    async def get_diplomacy(self) -> list[Any]: ...
    async def get_map_area(self, center_x: int, center_y: int, radius: int = 2) -> list[Any]: ...
    async def list_city_production(self, city_id: int) -> list[Any]: ...
    async def check_game_over(self) -> Any | None: ...

    # Reads Napoleon adds -------------------------------------------------------------
    async def end_turn_blockers(self) -> list[tuple[str, str]]:
        """``(ENDTURN_BLOCKING_*, message)`` pairs, empty when the turn can end."""
        ...

    async def ready_unit_ids(self) -> list[int]:
        """Composite ids of the player's units that still want orders this turn."""
        ...

    # Actions (civ6-mcp GameState) ----------------------------------------------------
    async def load_game_save(self, save_name: str) -> str: ...
    async def move_unit(self, unit_index: int, target_x: int, target_y: int) -> str: ...
    async def attack_unit(self, unit_index: int, target_x: int, target_y: int) -> str: ...
    async def found_city(self, unit_index: int) -> str: ...
    async def fortify_unit(self, unit_index: int) -> str: ...
    async def skip_unit(self, unit_index: int) -> str: ...
    async def set_city_production(self, city_id: int, item_type: str, item_name: str) -> str: ...
    async def set_research(self, tech_name: str) -> str: ...
    async def set_civic(self, civic_name: str) -> str: ...
    async def end_turn(self) -> str: ...


def is_error(result: str) -> bool:
    return result.lstrip().startswith(("Error", "ERR", "FAILED"))


def unit_index(unit_id: int) -> int:
    """civ6-mcp's per-player unit index from a composite unit id."""
    return unit_id % 65536
